#!/usr/bin/env python3
"""mknative.py -- assemble lib/native.asm into the prelude's NATIVE block.

The prelude may embed machine code as raw blobs (`N bytes`, which push their
address) and run it with ⍎ (pop rax; call rax).  lib/native.asm holds every
routine, each starting at a line `;; @word ‹name›`.  This tool assembles each
one with nasm (-f bin, BITS 64), checks that every byte can be written in a
.golfj blob, and rewrites the block between the NATIVE markers in
lib/prelude.golfj with one `:‹name›`N …⍎;` definition per routine.

A blob byte cannot be 0xF0-0xFF (no glyph), 0x23 (`#` starts a comment),
0x8E (the string delimiter), 0x0D (text-mode newline translation), 0x5C
(the decoders write it as a bare `\`, which reads back as a mnemonic) or
0xB4/0xB5 (the long-name brackets, which tools scan for).  So: no rep prefixes (F3), no FF-group (inc/dec/jmp reg: use
add/sub and push+ret), no negative displacements, and backward short jumps
must span more than 16 bytes (rel8 0x80-0xEF).

Convention: on entry [rsp] is the return address and the Golf data stack
(TOS first) is above it.  Routines pop the return address into r11, pop their
arguments, push their results and return with push r11; ret.  Compiled Golf
uses only rax rcx rdx rsi rdi rbp rsp, so r8-r15 and rbx are free.

  python3 tools/mknative.py          rewrite the block
  python3 tools/mknative.py --check  exit 1 if the block is stale (needs nasm)
"""
import os, re, subprocess, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import codepage as c  # noqa: E402

ROOT = os.path.dirname(HERE)
ASM = os.path.join(ROOT, "lib", "native.asm")
PRE = os.path.join(ROOT, "lib", "prelude.golfj")
BEGIN = "# === NATIVE: generated by tools/mknative.py from lib/native.asm, do not edit ===\n"
END = "# === END NATIVE ===\n"
BAD = set(range(0xF0, 0x100)) | {0x23, 0x8E, 0x0D, 0x5C, 0xB4, 0xB5}
INV = {v: k for k, v in c.GLYPH2BYTE.items()}


def text(bs):
    out = []
    for i, b in enumerate(bs):
        if b in BAD:
            raise ValueError(f"byte {b:02X} at offset {i}")
        out.append("\\\\" if b == 0x5C else chr(b) if b < 0x80 else INV[b])
    s = "`%d " % len(bs) + "".join(out)
    assert c.encode(s) == b"`" + str(len(bs)).encode() + b" " + bs
    return s


def build():
    src = open(ASM).read()
    parts = re.split(r"^;; @word (‹[^›]+›)[^\n]*\n", src, flags=re.M)
    head, defs = parts[0], []
    for name, body in zip(parts[1::2], parts[2::2]):
        with tempfile.TemporaryDirectory() as t:
            a, o = os.path.join(t, "a.asm"), os.path.join(t, "a.bin")
            open(a, "w").write("BITS 64\n" + head + body)
            subprocess.run(["nasm", "-f", "bin", "-o", o, a], check=True)
            bs = open(o, "rb").read()
        try:
            defs.append(f":{name}{text(bs)}⍎;\n")
        except ValueError as e:
            sys.exit(f"mknative: {name}: {e}")
    return BEGIN + "".join(defs) + END


def main():
    new = build()
    pre = open(PRE, encoding="utf-8", newline="").read()
    i, j = pre.index(BEGIN), pre.index(END) + len(END)
    if "--check" in sys.argv:
        if pre[i:j] != new:
            sys.exit("mknative: the NATIVE block is stale: python3 tools/mknative.py")
        print("mknative: NATIVE block up to date")
        return
    open(PRE, "w", encoding="utf-8", newline="").write(pre[:i] + new + pre[j:])


if __name__ == "__main__":
    main()
