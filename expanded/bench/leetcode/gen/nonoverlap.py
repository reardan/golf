def gen(R, S, w):
    n = max(4, int(300000 * S)); a = []
    for _ in range(n):
        s = R.randint(-5 * 10**4, 5 * 10**4 - 1); a += [s, min(5 * 10**4, s + R.randint(1, 200))]
    w('', ' '.join(map(str, a)) + '\n')
    w('2', '1 2 2 3 3 4 1 3\n'); w('3', '1 2 1 2 1 2\n'); w('4', '1 2 2 3\n'); w('5', '5 9\n')
    w('6', '-3 -1 -2 0 -1 1 0 2\n'); w('7', '1 100 11 22 1 11 2 12\n'); w('8', '0 2 1 3 2 4 3 5 4 6\n')
