    n = max(4, int(500000 * S))
    w('', ' '.join(str(R.randint(-n, n)) for _ in range(n)) + '\n')
    w('2', '100 4 200 1 3 2\n'); w('3', '0 3 7 2 5 8 4 6 0 1\n'); w('4', '\n'); w('5', '1 2 0 1\n')
    w('6', '-1 -3 -2\n'); w('7', '5\n'); w('8', '7 7 7\n'); w('9', '9 1 -3 2 4 8 3 -1 -2 6 0\n')
