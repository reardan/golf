    n = max(4, int(500000 * S))
    w('', ' '.join(str(R.randint(0, 10**4)) for _ in range(n)) + '\n')
    w('2', '2 1 5 6 2 3\n'); w('3', '2 4\n'); w('4', '0\n'); w('5', '5\n'); w('6', '1 1 1 1\n')
    w('7', '0 0\n'); w('8', '3 2 1\n'); w('9', '1 2 3 4 5\n'); w('10', '4 0 4 4 0 2\n')
