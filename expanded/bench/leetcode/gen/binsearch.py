def gen(R, S, w):
    n = max(4, int(1000000 * S)); a = sorted(R.sample(range(-10**9, 10**9), n))
    w('', f'{a[R.randrange(n)]}\n' + ' '.join(map(str, a)) + '\n')
    w('2', '9\n-1 0 3 5 9 12\n'); w('3', '2\n-1 0 3 5 9 12\n'); w('4', '5\n5\n'); w('5', '-5\n5\n')
    w('6', '13\n-1 0 3 5 9 12\n'); w('7', '-2\n-1 0 3 5 9 12\n'); w('8', '-1\n-1 0 3 5 9 12\n')
