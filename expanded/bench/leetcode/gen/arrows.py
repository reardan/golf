def gen(R, S, w):
    n = max(4, int(300000 * S)); a = []
    for _ in range(n):
        s = R.randint(-2**31, 2**31 - 1); a += [s, min(2**31 - 1, s + R.randint(0, 2**22))]
    w('', ' '.join(map(str, a)) + '\n')
    w('2', '10 16 2 8 1 6 7 12\n'); w('3', '1 2 3 4 5 6 7 8\n'); w('4', '1 2 2 3 3 4 4 5\n'); w('5', '3 3\n')
    w('6', '-2147483648 2147483647\n'); w('7', '1 2 1 2 1 2\n'); w('8', '-5 -3 -4 -1 0 0 -3 0\n')
