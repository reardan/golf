def gen(R, S, w):
    n = max(4, int(200000 * S)); a = []
    for _ in range(n):
        s = R.randint(0, 10**7); a += [s, s + R.randint(0, 100)]
    w('', ' '.join(map(str, a)) + '\n')
    w('2', '1 3 2 6 8 10 15 18\n'); w('3', '1 4 4 5\n'); w('4', '1 4 0 4\n'); w('5', '1 4 2 3\n')
    w('6', '5 5\n'); w('7', '1 4 0 0\n'); w('8', '2 2 2 2 2 3\n'); w('9', '4 7 1 2 3 3 9 9 0 10\n')
