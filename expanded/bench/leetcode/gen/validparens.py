def gen(R, S, w):
    n = max(4, int(2000000 * S))
    w('', ''.join(R.choice('(()') if R.random() < 0.5 else R.choice('())') for _ in range(n)) + '\n')
    w('2', '(()\n'); w('3', ')()())\n'); w('4', '\n'); w('5', '()(()\n'); w('6', '((((\n'); w('7', '))))\n')
    w('8', '()(())\n'); w('9', ')(\n'); w('10', '(()())(()\n')
